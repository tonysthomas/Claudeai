// Ingestion pipeline: source → extract → normalize → Phase 3 import preview →
// commit plan → relationship engine → emit (SQL / demo module). All data flows
// through the existing Phase 3 catalogue importer (buildImportPreview/planCommit)
// so the same validation, dedupe, and safe-approval guarantees apply. Approval
// stays pending_review unless --auto-approve is passed (an explicit action).
import { buildImportPreview, planCommit, type ImportContext, type ImportPreview, type CommitPlan, type ExistingCatalogue } from '../../src/import/index';
import { extractProduct } from './extractor';
import { normalizeProduct } from './normalize';
import { generateRelationships, type GeneratedRelationship, type IngestProduct } from './relationshipEngine';
import type { IngestOptions, NormalizedIngestRow, SkechersSource } from './types';

export interface IngestResult {
  batch: IngestOptions & { styles: string[]; sourceName: string };
  preview: ImportPreview;
  plan: CommitPlan;
  rows: NormalizedIngestRow[]; // valid, normalized rows to persist
  approvalStatus: 'approved' | 'pending_review';
  relationships: GeneratedRelationship[];
}

/** Run the full pipeline for a set of style numbers. */
export async function runIngest(params: {
  styles: string[];
  source: SkechersSource;
  opts: IngestOptions;
  existing?: ExistingCatalogue;
}): Promise<IngestResult> {
  const { styles, source, opts, existing } = params;

  const raw = await source.fetchMany(styles);
  const extracted = raw.map(extractProduct);
  const normalized = extracted.map((e) => normalizeProduct(e, opts));

  // Feed the canonical rows through the Phase 3 importer (validation + dedupe).
  const ctx: ImportContext = {
    fileName: `skechers-ingest-${opts.syncedAt}.json`,
    fileFormat: 'json',
    sourceType: 'skechers_official_web',
    sourceUrl: null,
    region: opts.region,
    currency: opts.currency,
    importedBy: opts.importedBy,
    importedAt: opts.syncedAt,
    existing,
  };
  const preview = buildImportPreview(JSON.stringify(normalized.map((n) => n.row)), ctx);
  const plan = planCommit(preview, { allowOverwriteApproved: false });

  // Keep only rows that validated (by SKU) for persistence + relationship wiring.
  const validSkus = new Set(preview.rows.filter((r) => r.status === 'valid').map((r) => r.normalized?.sku));
  const rows = normalized.filter((n) => validSkus.has(n.sku));

  const approvalStatus = opts.autoApprove ? 'approved' : 'pending_review';

  const ingestProducts: IngestProduct[] = rows.map((n) => ({
    sku: n.sku,
    name: String(n.row.name),
    category: String(n.row.category),
    subcategory: (n.row.subcategory as string | null) ?? null,
    activity_type: (n.row.activity_type as string | null) ?? null,
    technology: (n.row.technology as string | null) ?? null,
    price: (n.row.price as number | null) ?? null,
    priceTier: n.priceTier,
    region: String(n.row.region),
  }));
  const relationships = generateRelationships(ingestProducts);

  return { batch: { ...opts, styles, sourceName: source.name }, preview, plan, rows, approvalStatus, relationships };
}

// --------------------------------------------------------------------------
// Emitters
// --------------------------------------------------------------------------

const sq = (v: unknown): string => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const numOrNull = (v: unknown): string => (v === null || v === undefined || v === '' ? 'null' : String(Number(v)));
const jsonbOrNull = (v: unknown): string => (Array.isArray(v) && v.length > 0 ? `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb` : 'null');

/** Emit an idempotent SQL script that imports the batch through the real tables. */
export function resultToSql(result: IngestResult): string {
  const { batch, rows, relationships, approvalStatus, preview } = result;
  const approvedBy = batch.autoApprove ? "'skechers_ingest'" : 'null';
  const approvedAt = batch.autoApprove ? 'now()' : 'null';
  const skus = rows.map((r) => sq(r.sku)).join(', ');

  const lines: string[] = [];
  lines.push('-- AUTO-GENERATED by scripts/ingest-skechers.ts — do not edit by hand.');
  lines.push(`-- Source: ${batch.sourceName} · region=${batch.region} · synced_at=${batch.syncedAt} · approval=${approvalStatus}`);
  lines.push('-- Provenance: source_type=skechers_official_web (authorized ingestion; no live scraping).');
  lines.push('begin;');
  lines.push('');

  // 1. Import batch record (traceability).
  lines.push('insert into public.catalogue_imports');
  lines.push('  (file_name, file_format, source_type, region, currency, status, total_rows, valid_rows, invalid_rows, committed_rows, imported_by, imported_at)');
  lines.push(`values (${sq(preview.fileName)}, 'json', 'skechers_official_web', ${sq(batch.region)}, ${sq(batch.currency)}, 'committed', ${preview.totalRows}, ${preview.validRows}, ${preview.invalidRows}, ${rows.length}, ${sq(batch.importedBy)}, ${sq(batch.syncedAt)});`);
  lines.push('');

  // 2. Upsert products (reject duplicate SKUs by UPDATING price/image only).
  lines.push('insert into public.products');
  lines.push('  (sku, style_number, name, category, subcategory, gender, color, size_range, price, currency, region,');
  lines.push('   image_url, product_url, description, key_features, technology, activity_type,');
  lines.push('   source_type, source_url, source_identifier, source_version, data_status, approval_status, approved_by, approved_at, last_synced_at, imported_at)');
  lines.push('values');
  const productValues = rows.map((n) => {
    const r = n.row;
    return `  (${sq(r.sku)}, ${sq(r.style_number)}, ${sq(r.name)}, ${sq(r.category)}, ${sq(r.subcategory)}, ${sq(r.gender)}, ${sq(r.color)}, ${sq(r.size_range)}, ${numOrNull(r.price)}, ${sq(r.currency)}, ${sq(r.region)}, ${sq(r.image_url)}, ${sq(r.product_url)}, ${sq(r.description)}, ${jsonbOrNull(r.key_features)}, ${sq(r.technology)}, ${sq(r.activity_type)}, 'skechers_official_web', ${sq(r.source_url)}, ${sq(r.source_identifier)}, ${sq(r.source_version)}, 'imported', ${sq(approvalStatus)}, ${approvedBy}, ${approvedAt}, ${sq(batch.syncedAt)}, now())`;
  });
  lines.push(productValues.join(',\n') + '');
  lines.push('on conflict (sku) do update set');
  lines.push('  price = excluded.price,');
  lines.push('  image_url = excluded.image_url,');
  lines.push('  product_url = excluded.product_url,');
  lines.push('  last_synced_at = excluded.last_synced_at,');
  lines.push("  data_status = 'changed',");
  lines.push('  updated_at = now();');
  lines.push('');

  // 3. Provenance rows (refresh for these SKUs).
  lines.push(`delete from public.product_sources where source_type = 'skechers_official_web' and product_id in (select id from public.products where sku in (${skus}));`);
  lines.push('insert into public.product_sources');
  lines.push('  (product_id, source_type, source_url, source_identifier, source_region, source_version, permission_status, synced_at, approval_status, approved_by, approved_at)');
  lines.push('select p.id, ' + "'skechers_official_web', p.source_url, p.source_identifier, p.region, p.source_version, 'granted', " + sq(batch.syncedAt) + `, ${sq(approvalStatus)}, ${approvedBy}, ${approvedAt}`);
  lines.push(`from public.products p where p.sku in (${skus});`);
  lines.push('');

  // 4. Relationships (refresh those originating from these SKUs, then insert).
  lines.push(`delete from public.product_relationships where source_product_id in (select id from public.products where sku in (${skus}));`);
  for (const rel of relationships) {
    lines.push('insert into public.product_relationships');
    lines.push('  (source_product_id, target_product_id, relationship_type, priority, reason, customer_benefit, activity_type, customer_need, region, active, approval_status)');
    lines.push(`select s.id, t.id, ${sq(rel.relationship_type)}, ${rel.priority}, ${sq(rel.reason)}, ${sq(rel.customer_benefit)}, ${sq(rel.activity_type)}, ${sq(rel.customer_need)}, ${sq(batch.region)}, true, ${sq(approvalStatus)}`);
    lines.push(`from public.products s, public.products t where s.sku = ${sq(rel.sourceSku)} and t.sku = ${sq(rel.targetSku)};`);
  }
  lines.push('');
  lines.push('commit;');
  lines.push('');
  return lines.join('\n');
}

/** Emit a TS module the browser demo imports so the app can show the real products. */
export function resultToDemoModule(result: IngestResult): string {
  const { rows, relationships } = result;
  const products = rows.map((n) => {
    const r = n.row;
    return {
      sku: r.sku, style_number: r.style_number, name: r.name, category: r.category, subcategory: r.subcategory,
      gender: r.gender, color: r.color, size_range: r.size_range, price: r.price, currency: r.currency, region: r.region,
      product_url: r.product_url, description: r.description, key_features: r.key_features, technology: r.technology,
      activity_type: r.activity_type,
    };
  });
  const edges = relationships.map((rel) => ({
    source: rel.sourceSku, target: rel.targetSku, type: rel.relationship_type, priority: rel.priority,
    reason: rel.reason, benefit: rel.customer_benefit, need: rel.customer_need,
  }));
  return [
    '// AUTO-GENERATED by scripts/ingest-skechers.ts — do not edit by hand.',
    '// Real (authorized-sample) Skechers records + generated relationships for the',
    '// browser demo. Images are omitted here (referenced by URL in the DB), so the',
    '// demo renders category placeholders — it never hotlinks skechers.com assets.',
    "import type { IngestedDemoProduct, IngestedDemoEdge } from './ingestedTypes';",
    '',
    `export const INGESTED_PRODUCTS: IngestedDemoProduct[] = ${JSON.stringify(products, null, 2)};`,
    '',
    `export const INGESTED_EDGES: IngestedDemoEdge[] = ${JSON.stringify(edges, null, 2)};`,
    '',
  ].join('\n');
}
